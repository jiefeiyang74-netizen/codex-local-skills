from __future__ import annotations

import json
import pprint
from pathlib import Path
from typing import Any

from .storyboard import storyboard_timeline


TEMPLATE_PATH = Path(__file__).with_name("runtime_template.py")
MARKER = "STORYBOARD_SPEC = {}  # __INJECT_STORYBOARD__"
MOTION_MARKER = "from v3.part_motion import grid_positions, assert_piece_count, part_state_issues  # __INJECT_PART_MOTION__"
EQUATION_MARKER = "from v3.equation_motion import equation_motion_tokens, equation_sum_mapping  # __INJECT_EQUATION_MOTION__"
CIRCLE_MAX_MARKER = "from v3.circle_max_motion import play_circle_linear_max  # __INJECT_CIRCLE_MAX_MOTION__"
CAUCHY_MIN_MARKER = "from v3.cauchy_min_motion import play_cauchy_linear_min  # __INJECT_CAUCHY_MIN_MOTION__"


def compile_storyboard(spec: dict[str, Any]) -> tuple[str, list[dict[str, Any]]]:
    template = TEMPLATE_PATH.read_text(encoding="utf-8")
    if template.count(MARKER) != 1:
        raise RuntimeError("v3 本地运行模板注入标记损坏")
    if template.count(MOTION_MARKER) != 1:
        raise RuntimeError("等份动作模块注入标记损坏")
    template = template.replace(MOTION_MARKER, TEMPLATE_PATH.with_name("part_motion.py").read_text(encoding="utf-8"))
    if template.count(EQUATION_MARKER) != 1:
        raise RuntimeError("等式搬运动作模块注入标记损坏")
    template = template.replace(EQUATION_MARKER, TEMPLATE_PATH.with_name("equation_motion.py").read_text(encoding="utf-8"))
    if template.count(CIRCLE_MAX_MARKER) != 1:
        raise RuntimeError("圆约束最值动作模块注入标记损坏")
    template = template.replace(CIRCLE_MAX_MARKER, TEMPLATE_PATH.with_name("circle_max_motion.py").read_text(encoding="utf-8"))
    if template.count(CAUCHY_MIN_MARKER) != 1:
        raise RuntimeError("柯西最小值动作模块注入标记损坏")
    template = template.replace(CAUCHY_MIN_MARKER, TEMPLATE_PATH.with_name("cauchy_min_motion.py").read_text(encoding="utf-8"))
    literal = pprint.pformat(spec, width=110, sort_dicts=False, compact=False)
    timeline = storyboard_timeline(spec)
    header = (
        "# Generated by Manim Prompt Studio v4.9 deterministic word-synchronised reference-motion compiler.\n"
        "# The chosen model plans new storyboards; the local workbench compiles safe animation components.\n"
        f"# STORYBOARD_TIMELINE={json.dumps(timeline, ensure_ascii=False, separators=(',', ':'))}\n"
    )
    code = template.replace(MARKER, f"STORYBOARD_SPEC = {literal}")
    return header + code, timeline
